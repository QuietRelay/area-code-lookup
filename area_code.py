def lookup(code: str) -> str:
    """Return a human-readable location string for a given input, which may
    be a bare 3-digit area code or a longer number (e.g. 10-digit)."""
    digits = "".join(ch for ch in code if ch.isdigit())

    if not digits:
        return "No digits found in input."

    # Strip a leading country code "1" if present (e.g. +1-415-555-1234)
    if len(digits) > 3 and digits.startswith("1"):
        digits = digits[1:]

    area = digits[:3]

    if len(area) != 3:
        return f"'{code}' doesn't contain a valid 3-digit area code."

    return AREA_CODES.get(area, f"Area code {area} was not found in the local database.")


def run_lookup_and_print(raw: str) -> None:
    digits = "".join(ch for ch in raw if ch.isdigit())
    area = digits[1:4] if len(digits) > 3 and digits.startswith("1") else digits[:3]
    result = lookup(raw)
    print(f"{area or raw} -> {result}")


def main() -> None:
    args = sys.argv[1:]

    if args:
        for arg in args:
            run_lookup_and_print(arg)
        return

    print("American/Canadian (NANP) Area Code Lookup")
    print("Enter an area code (or full number). Type 'q' to quit.\n")
    while True:
        try:
            raw = input("Area code: ").strip()
        except (EOFError, KeyboardInterrupt):
            print()
            break
        if not raw or raw.lower() in ("q", "quit", "exit"):
            break
        run_lookup_and_print(raw)


if __name__ == "__main__":
    main()
